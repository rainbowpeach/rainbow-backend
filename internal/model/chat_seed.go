func SeedChatPersonas(db *gorm.DB) error {
	for _, persona := range defaultChatPersonas() {
		var existing ChatPersona
		err := db.Where("scene_code = ?", persona.SceneCode).First(&existing).Error
		if err == nil {
			continue
		}
		if !errors.Is(err, gorm.ErrRecordNotFound) {
			return fmt.Errorf("find chat persona %s: %w", persona.SceneCode, err)
		}
		if err := db.Create(&persona).Error; err != nil {
			return fmt.Errorf("seed chat persona %s: %w", persona.SceneCode, err)
		}
	}

	return nil
}
